#!/usr/bin/env node
// Rebuilds PROJECTS.md — the cross-project inventory this repo keeps an eye on.
//
// Read-only against both services: it lists every Worker in the account and every
// repo on the owner, plus whether each repo carries a README, an AGENTS file and a
// Wrangler config. Nothing but PROJECTS.md is written. Needs CLOUDFLARE_API_TOKEN
// and GITHUB_PAT_TOKEN in the environment.
//
//   node scripts/overview.mjs
//
// Hand-written rules belong in AGENTS.md. This file is regenerated wholesale, so
// an edit here survives only until the next run.

import { writeFileSync } from "node:fs";

const OWNER = "dno-luigi";
const OUT = new URL("../PROJECTS.md", import.meta.url);

// Workers whose name differs from their repo's.
const ALIASES = {
  "vibe-microsite-builder": "vibe",
  memkv: "memKV",
};

const cfHeaders = { Authorization: `Bearer ${process.env.CLOUDFLARE_API_TOKEN}` };
const ghHeaders = {
  Authorization: `Bearer ${process.env.GITHUB_PAT_TOKEN}`,
  "User-Agent": "mind-overview",
  Accept: "application/vnd.github+json",
};

async function get(url, headers) {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

// A bounded pool: 100 sequential requests to the contents API is slow enough to
// look like a hang, and an unbounded fan-out is rude to the API.
async function pool(items, limit, work) {
  const out = new Array(items.length);
  let next = 0;
  async function run() {
    while (next < items.length) {
      const index = next;
      next += 1;
      out[index] = await work(items[index], index);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, run));
  return out;
}

const accounts = await get("https://api.cloudflare.com/client/v4/accounts", cfHeaders);
const accountId = accounts.result?.[0]?.id;
if (!accountId) throw new Error("no account id — is CLOUDFLARE_API_TOKEN set?");

const scripts = await get(
  `https://api.cloudflare.com/client/v4/accounts/${accountId}/workers/scripts`,
  cfHeaders,
);
const workers = scripts.result
  .map((s) => ({ name: s.id, deployed: (s.modified_on || "").slice(0, 10) }))
  .sort((a, b) => a.name.localeCompare(b.name));

const repos = [];
for (let page = 1; ; page += 1) {
  const batch = await get(
    `https://api.github.com/users/${OWNER}/repos?per_page=100&page=${page}`,
    ghHeaders,
  );
  repos.push(...batch);
  if (batch.length < 100) break;
}

const docState = await pool(repos, 8, async (repo) => {
  const files = await get(
    `https://api.github.com/repos/${OWNER}/${repo.name}/contents/`,
    ghHeaders,
  ).catch(() => []);
  const names = Array.isArray(files) ? files.map((f) => f.name) : [];
  return {
    readme: names.some((n) => /^readme(\.|$)/i.test(n)),
    agents: names.some((n) => /^agents(\.[a-z]+)?$/i.test(n)),
    wrangler: names.some((n) => /^wrangler\.(jsonc|json|toml)$/i.test(n)),
  };
});

const docs = new Map(repos.map((repo, i) => [repo.name, docState[i]]));
const byName = new Map(repos.map((repo) => [repo.name.toLowerCase(), repo]));

const repoFor = (worker) => {
  const target = (ALIASES[worker] || worker).toLowerCase();
  return byName.get(target) || null;
};

const paired = workers.filter((w) => repoFor(w.name));
const orphans = workers.filter((w) => !repoFor(w.name));
const pairedNames = new Set(paired.map((w) => repoFor(w.name).name));

const mark = (value) => (value ? "yes" : "—");

const workerRows = workers.map((w) => {
  const repo = repoFor(w.name);
  const state = repo ? docs.get(repo.name) : null;
  return `| \`${w.name}\` | ${w.deployed || "—"} | ${repo ? `\`${repo.name}\`` : "—"} | ${state ? mark(state.readme) : "—"} | ${state ? mark(state.agents) : "—"} |`;
});

const other = repos
  .filter((repo) => !pairedNames.has(repo.name))
  .sort((a, b) => Number(a.fork) - Number(b.fork) || (b.pushed_at || "").localeCompare(a.pushed_at || ""));

const otherRows = other.map((repo) => {
  const state = docs.get(repo.name) || {};
  return `| \`${repo.name}\` | ${repo.fork ? "fork" : "own"} | ${(repo.pushed_at || "").slice(0, 10)} | ${mark(state.readme)} | ${mark(state.agents)} | ${mark(state.wrangler)} |`;
});

const wranglerNoAgents = repos.filter((repo) => {
  const state = docs.get(repo.name) || {};
  return state.wrangler && !state.agents;
});
const noReadme = repos.filter((repo) => !(docs.get(repo.name) || {}).readme);
const agentsNoRepo = workers.filter((w) => !repoFor(w.name)).length;

const today = new Date().toISOString().slice(0, 10);

const markdown = `# Projects

Every Worker in the account and every repo on \`${OWNER}\`, as of **${today}**.

Generated by \`node scripts/overview.mjs\` — re-run it rather than editing this
file. Rules about how these projects are documented live in
[AGENTS.md](AGENTS.md), not here.

- **${workers.length}** Workers, **${repos.length}** repos (${repos.filter((r) => r.fork).length} forks).
- **${paired.length}** Workers name a repo of the same name; **${orphans.length}** have no
  matching repo — their source is not on GitHub under that name.
- **${wranglerNoAgents.length}** repos carry a Wrangler config but no AGENTS file.
- **${noReadme.length}** repos have no README.

## Workers

\`README\` and \`AGENTS\` describe the **repo**, not the deployed Worker; a Worker can
be newer than its repo. \`—\` means no repo of that name exists.

| worker | last deploy | repo | README | AGENTS |
| --- | --- | --- | --- | --- |
${workerRows.join("\n")}

## Repos with no Worker of the same name

Own repos first, then forks. A Worker serves the name; a repo can exist without
one being deployed from it.

| repo | kind | last push | README | AGENTS | wrangler |
| --- | --- | --- | --- | --- | --- |
${otherRows.join("\n")}

## Documentation gaps

Wrangler config but no AGENTS file — these are the candidates for a rules file,
written here in \`mind\` and pointed back at it:

${wranglerNoAgents.length ? wranglerNoAgents.map((r) => `- \`${r.name}\``).join("\n") : "- none"}

No README at all:

${noReadme.length ? noReadme.map((r) => `- \`${r.name}\``).join("\n") : "- none"}

## Workers whose source is not in a same-named repo

${orphans.length ? orphans.map((w) => `- \`${w.name}\` (deployed ${w.deployed || "unknown"})`).join("\n") : "- none"}
`;

writeFileSync(OUT, markdown);

console.log(
  [
    `wrote PROJECTS.md`,
    `workers=${workers.length}`,
    `repos=${repos.length}`,
    `paired=${paired.length}`,
    `orphan_workers=${agentsNoRepo}`,
    `wrangler_no_agents=${wranglerNoAgents.length}`,
    `no_readme=${noReadme.length}`,
  ].join(" "),
);
