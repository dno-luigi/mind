#!/usr/bin/env node
/**
 * src/prompts.js is generated from the .md files beside it.
 *
 * The prompts are the owner's text: they stay in files a person can read, diff
 * and edit. The module exists only because a Worker cannot read a file at
 * runtime and the test suite runs on plain Node, which cannot import .md.
 *
 * Run after editing a prompt: node scripts/gen-prompts.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(import.meta.dirname, '..', 'src', 'prompts');
const sources = [
  ['TRUTH_PROMPT', 'truth'],
  ['MNL_PROMPT', 'mnl'],
  ['MICRO_PROMPT', 'micro'],
  ['DOC_PROMPT', 'doc'],
];

let out = '// Generated by scripts/gen-prompts.mjs from src/prompts/*.md — edit those files.\n';
for (const [name, file] of sources) {
  const text = fs.readFileSync(path.join(dir, `${file}.md`), 'utf8').replace(/\n+$/, '');
  out += `\nexport const ${name} = ${JSON.stringify(text)};\n`;
}

fs.writeFileSync(path.join(dir, '..', 'prompts.js'), out);
console.log(`src/prompts.js written from ${sources.length} prompt files`);
